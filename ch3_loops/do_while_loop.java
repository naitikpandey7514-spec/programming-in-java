
// do while loop used to execute block of code repeatedly . it executed at least one time even if the condition is not true.
/*
syntax;
do{
//code
}while(condition);

 */

//example

public class do_while_loop{
    public static void main(String[] args){
        int num = 1;
        do{
            System.out.println("utu");
            num++;
        }while(num<=5);

    }
}